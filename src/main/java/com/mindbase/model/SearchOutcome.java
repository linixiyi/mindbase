package com.mindbase.model;

/**
 * 检索结果分类（task_0005）：正常命中 + 三种失败分类。
 * 工具结果提示文本、日志观测按此分类区分，不再把所有失败一律当"未检索到"。
 */
public enum SearchOutcome {
    /**
     * 正常命中：检索链路跑通并返回结果（含向量/重排降级后仍有结果的场景，
     * 以及索引中确实无匹配的空结果——空结果时结果列表为空但检索本身成功）
     */
    HIT,
    /**
     * 权限解析失败：无法为当前用户构造权限过滤条件，未执行任何检索，结果为空
     */
    NO_PERMISSION_MATCH,
    /**
     * 召回失败：混合检索与纯文本兜底均抛异常，未得到可用结果，结果为空
     */
    RECALL_FAILED,
    /**
     * 阈值全滤：rerank 后无候选达到分数阈值，已按 RRF 融合排序返回前 N 条兜底，结果非空
     */
    BELOW_THRESHOLD
}
