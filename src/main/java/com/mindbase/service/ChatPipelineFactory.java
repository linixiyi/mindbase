package com.mindbase.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.mindbase.config.ChatDeadlineProperties;
import com.mindbase.service.citation.CitationVerificationService;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.data.redis.core.RedisTemplate;
import org.springframework.scheduling.concurrent.ThreadPoolTaskExecutor;
import org.springframework.stereotype.Service;

/**
 * 生产 WS 链路与评测 headless 链路共用的 {@link ChatPipeline} 装配点（task-0010 / C10）：
 * 工具注册表、ReAct 最大轮数、提示词（经同一 {@link LlmProviderRouter} 装配）、模型路由与
 * 截止时间都只在这里装配一次，{@link ChatHandler}（生产）与 {@code RagEvalCaseRunner}（评测）
 * 都从这里取实例，不再各自 new ChatPipeline(...) 靠人肉保持一致。
 * <p>
 * 两条链路本来存在的差异显式建模为装配参数，不允许用 null 隐式表达：
 * <ul>
 *   <li>会话基础设施（redis/限流/会话/生成快照/注册表/监控线程池）：生产齐备注入；
 *       headless 用 {@link SessionInfra#none()} 显式表达"无会话"；</li>
 *   <li>引用校验：生产装配固定开启（实际生效还取决于 ai.citation-verification.enabled）；
 *       headless 装配显式传 {@code citationVerificationEnabled=false}。</li>
 * </ul>
 * 一致性由契约测试 {@code ChatPipelineParityTest} 固化：maxRounds、工具名集合、模型 provider、
 * system prompt 哈希两边一致，且 headless 构造不依赖 WebSocketSession。
 *
 * @author Generated by Assistant
 */
@Service
public class ChatPipelineFactory {

    /**
     * ReAct 最大轮数：两条链路唯一的取值来源（原 ChatPipeline.MAX_REACT_ROUNDS 常量迁到这里），
     * 由装配传入 pipeline 实例，契约测试断言两边一致
     */
    public static final int MAX_REACT_ROUNDS = 4;

    // —— 两条链路共用的装配件（一致性契约的载体）——
    private final HybridSearchService searchService;
    private final LlmProviderRouter llmProviderRouter;
    private final AgentToolRegistry agentToolRegistry;
    private final ObjectMapper objectMapper;
    private final ChatDeadlineProperties deadlineProperties;
    // —— 仅生产链路需要：会话基础设施与引用校验服务 ——
    private final SessionInfra sessionInfra;
    private final CitationVerificationService citationVerificationService;

    /** Spring 装配：共享链路配置 + 生产会话基础设施全部注入 */
    @Autowired
    public ChatPipelineFactory(HybridSearchService searchService,
                               LlmProviderRouter llmProviderRouter,
                               AgentToolRegistry agentToolRegistry,
                               ObjectMapper objectMapper,
                               ChatDeadlineProperties deadlineProperties,
                               RedisTemplate<String, String> redisTemplate,
                               RateLimitService rateLimitService,
                               ConversationService conversationService,
                               ChatGenerationStateService chatGenerationStateService,
                               ChatSessionRegistry chatSessionRegistry,
                               CitationVerificationService citationVerificationService,
                               @Qualifier("chatMonitorExecutor") ThreadPoolTaskExecutor chatMonitorExecutor) {
        this(searchService, llmProviderRouter, agentToolRegistry, objectMapper, deadlineProperties,
                new SessionInfra(redisTemplate, rateLimitService, conversationService,
                        chatGenerationStateService, chatSessionRegistry, chatMonitorExecutor),
                citationVerificationService);
    }

    ChatPipelineFactory(HybridSearchService searchService,
                        LlmProviderRouter llmProviderRouter,
                        AgentToolRegistry agentToolRegistry,
                        ObjectMapper objectMapper,
                        ChatDeadlineProperties deadlineProperties,
                        SessionInfra sessionInfra,
                        CitationVerificationService citationVerificationService) {
        this.searchService = searchService;
        this.llmProviderRouter = llmProviderRouter;
        this.agentToolRegistry = agentToolRegistry;
        this.objectMapper = objectMapper;
        this.deadlineProperties = deadlineProperties == null ? new ChatDeadlineProperties() : deadlineProperties;
        this.sessionInfra = sessionInfra == null ? SessionInfra.none() : sessionInfra;
        this.citationVerificationService = citationVerificationService;
    }

    /**
     * 离线装配（评测/测试）：只有共享链路配置，无会话基础设施，截止时间用默认值。
     * 评测 headless 链路的 pipeline 一律从这里构造，不再自行 new ChatPipeline(null, ...) 占位。
     */
    public static ChatPipelineFactory offline(HybridSearchService searchService,
                                              LlmProviderRouter llmProviderRouter,
                                              AgentToolRegistry agentToolRegistry,
                                              ObjectMapper objectMapper) {
        return new ChatPipelineFactory(searchService, llmProviderRouter, agentToolRegistry, objectMapper,
                new ChatDeadlineProperties(), SessionInfra.none(), null);
    }

    /** 生产 WS 链路：会话基础设施齐备，引用校验随装配开启 */
    public ChatPipeline createProductionPipeline() {
        return new ChatPipeline(searchService, llmProviderRouter, agentToolRegistry, objectMapper,
                deadlineProperties, MAX_REACT_ROUNDS, true, citationVerificationService, sessionInfra);
    }

    /** 评测 headless 链路：{@link SessionInfra#none()} 显式表达无会话，引用校验显式关闭（布尔传参，不是 null 占位） */
    public ChatPipeline createHeadlessPipeline() {
        return new ChatPipeline(searchService, llmProviderRouter, agentToolRegistry, objectMapper,
                deadlineProperties, MAX_REACT_ROUNDS, false, null, SessionInfra.none());
    }

    /** 两条链路统一的 ReAct 最大轮数 */
    public int maxRounds() {
        return MAX_REACT_ROUNDS;
    }

    /** 两条链路统一的提示词与模型路由入口：系统提示词经同一 router 的 buildReActMessages 装配 */
    public LlmProviderRouter llmProviderRouter() {
        return llmProviderRouter;
    }

    /** 两条链路统一的工具注册表 */
    public AgentToolRegistry agentToolRegistry() {
        return agentToolRegistry;
    }

    /** 两条链路统一的截止时间配置 */
    public ChatDeadlineProperties deadlineProperties() {
        return deadlineProperties;
    }

    /**
     * 会话基础设施集合：生产链路由 Spring 注入齐备；headless（评测）链路显式 {@link #none()}，
     * 不做会话、幂等、限流、落库与推送。用显式对象表达"无会话"，替代散落在构造参数里的 null 占位。
     */
    public record SessionInfra(
            RedisTemplate<String, String> redisTemplate,
            RateLimitService rateLimitService,
            ConversationService conversationService,
            ChatGenerationStateService chatGenerationStateService,
            ChatSessionRegistry chatSessionRegistry,
            ThreadPoolTaskExecutor chatMonitorExecutor
    ) {

        /** headless 链路的显式"无会话"标记 */
        public static SessionInfra none() {
            return new SessionInfra(null, null, null, null, null, null);
        }
    }
}
