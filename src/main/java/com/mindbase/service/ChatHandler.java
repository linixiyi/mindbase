package com.mindbase.service;

import com.mindbase.config.ChatDeadlineProperties;
import com.mindbase.service.citation.CitationVerificationService;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.data.redis.core.RedisTemplate;
import org.springframework.scheduling.concurrent.ThreadPoolTaskExecutor;
import org.springframework.stereotype.Service;
import org.springframework.web.socket.WebSocketSession;

import java.util.Map;

/**
 * 聊天处理的 WebSocket 适配器：把 {@link WebSocketSession} 的绑定与直接发送适配成
 * {@link ChatPipeline.SessionSink}，编排（ReAct 轮次、工具调用、引用装配、收尾落库）全部委托给
 * {@link ChatPipeline}，本类不再包含任何链路逻辑。
 * <p>
 * pipeline 按适配器各自实例化（状态全部按 generationId 隔离）：生产 WS 链路用本类持有的实例，
 * 由 {@link ChatPipelineFactory#createProductionPipeline()} 统一装配；离线评测 react 链路由
 * RagEvalCaseRunner 经 {@link ChatPipelineFactory#createHeadlessPipeline()} 以 headless 方式构造，
 * 两条链路的工具注册表/最大轮数/提示词/模型路由/截止时间由同一 factory 保证一致。
 *
 * @author Generated by Assistant
 */
@Service
public class ChatHandler {

    private static final org.slf4j.Logger logger = org.slf4j.LoggerFactory.getLogger(ChatHandler.class);

    private final ChatSessionRegistry chatSessionRegistry;
    private final ChatPipeline pipeline;

    /**
     * 生产装配（task-0010）：pipeline 经 {@link ChatPipelineFactory} 统一装配，本类只保留会话注册表做 sink 适配
     */
    @Autowired
    public ChatHandler(ChatPipelineFactory pipelineFactory, ChatSessionRegistry chatSessionRegistry) {
        this.chatSessionRegistry = chatSessionRegistry;
        this.pipeline = pipelineFactory.createProductionPipeline();
    }

    /**
     * @deprecated 生产装配已统一走 {@link ChatPipelineFactory#createProductionPipeline()}（上面的构造器）；
     * 本重载仅为既有测试保留，内部同样经由 factory 装配，生产链路不得再调用。
     */
    @Deprecated
    public ChatHandler(RedisTemplate<String, String> redisTemplate,
                      HybridSearchService searchService,
                      LlmProviderRouter llmProviderRouter,
                      RateLimitService rateLimitService,
                      ConversationService conversationService,
                      ChatGenerationStateService chatGenerationStateService,
                      ChatSessionRegistry chatSessionRegistry,
                      AgentToolRegistry agentToolRegistry,
                      CitationVerificationService citationVerificationService,
                      ObjectMapper objectMapper,
                      @Qualifier("chatMonitorExecutor") ThreadPoolTaskExecutor chatMonitorExecutor,
                      ChatDeadlineProperties deadlineProperties) {
        this.chatSessionRegistry = chatSessionRegistry;
        this.pipeline = new ChatPipelineFactory(searchService, llmProviderRouter, agentToolRegistry,
                objectMapper, deadlineProperties, redisTemplate, rateLimitService, conversationService,
                chatGenerationStateService, chatSessionRegistry, citationVerificationService, chatMonitorExecutor)
                .createProductionPipeline();
    }

    public void processMessage(String userId, String userMessage, WebSocketSession session) {
        processMessage(userId, userMessage, session, null);
    }

    public void processMessage(String userId, String userMessage, WebSocketSession session, String requestedConversationId) {
        logger.info("开始处理消息，用户ID: {}, 会话ID: {}", userId, session.getId());
        pipeline.processMessage(userId, userMessage, sessionSink(session), requestedConversationId);
    }

    /**
     * 当前连接的会话出口：pipeline 通过它做绑定/重挂/直接发送，不感知 WebSocketSession
     */
    private ChatPipeline.SessionSink sessionSink(WebSocketSession session) {
        return new ChatPipeline.SessionSink() {
            @Override
            public void sendJson(Map<String, ?> frame) {
                chatSessionRegistry.sendJsonToSession(session, frame);
            }

            @Override
            public void bindGeneration(String userId, String generationId) {
                chatSessionRegistry.bindGeneration(userId, generationId, session);
            }

            @Override
            public void resumeGeneration(String userId, String generationId) {
                chatSessionRegistry.resumeGeneration(userId, generationId, session);
            }
        };
    }

    /**
     * 停止响应
     */
    public void stopResponse(String userId, String generationId) {
        pipeline.stopResponse(userId, generationId);
    }

    /**
     * 根据引用编号获取文件MD5
     *
     * @param generationId    生成任务ID
     * @param referenceNumber 引用编号
     * @return 文件MD5，如果找不到则返回null
     */
    public String getReferenceMd5(String generationId, int referenceNumber) {
        return pipeline.getReferenceMd5(generationId, referenceNumber);
    }

    public ChatHandler.ReferenceInfo getReferenceDetail(String generationId, int referenceNumber) {
        return pipeline.getReferenceDetail(generationId, referenceNumber);
    }

    /**
     * search_knowledge 工具结果里的检索片段追加进引用映射（编号跨工具调用递增），返回带编号的片段文本。
     * 保留在本类上是为了既有测试与调用方不经过 pipeline 也能直接验证引用装配。
     */
    String appendReferencesFromSearchTool(String generationId,
                                          String userMessage,
                                          AgentToolRegistry.ToolExecutionResult toolResult) {
        return pipeline.appendReferencesFromSearchTool(generationId, userMessage, toolResult);
    }

    /**
     * 引用信息：引用编号到文件/分块/证据片段的映射。DocumentController 引用详情接口的既有公开类型，
     * pipeline 与适配器共用。
     */
    public record ReferenceInfo(
            String fileMd5,
            String fileName,
            Integer pageNumber,
            String anchorText,
            String retrievalMode,
            String retrievalLabel,
            String retrievalQuery,
            String matchedChunkText,
            String evidenceSnippet,
            Double score,
            Integer chunkId,
            /* 引用校验结论：SUPPORTED / SUSPICIOUS，未开启或未校验时为 null */
            String citationStatus,
            String citationReason
    ) {
        public ReferenceInfo withCitation(String status, String reason) {
            return new ReferenceInfo(fileMd5, fileName, pageNumber, anchorText, retrievalMode, retrievalLabel,
                    retrievalQuery, matchedChunkText, evidenceSnippet, score, chunkId, status, reason);
        }
    }

}
